// One-node-one-group is enforced by apply; the command asserts the
// absolute target membership and the group record CAS token.
struct AssignNodeToGroup {
  MetaRequestId request_id_{};
  ActorContext actor_;
  std::string group_id_;
  std::string node_id_;
  // The proposer generates a nonzero, globally unique value and never reuses
  // it for a later membership incarnation, including remove/re-add of the
  // same node. Apply persists the current/most-recent value and rejects its
  // immediate reuse; global uniqueness is the proposer-side contract.
  MetaAssignmentId assignment_id_{};
  MetaNodeRole role_ = MetaNodeRole::kPrimary;
  std::uint64_t expected_revision_ = 0;
  std::uint64_t new_topology_epoch_ = 0;  // absolute
  bool operator==(const AssignNodeToGroup&) const = default;
};

