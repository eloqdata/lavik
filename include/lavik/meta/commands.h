#pragma once

// MetaCommands defines the metadata control plane's committed command schema.
//
// Wire envelope (see encoding.h for primitives):
//   schema_version u16 | command_tag u16 | request_id 16B |
//   actor_principal str | readable_time str | command body
// Bodies are sequences of fixed-width LE integers, length-prefixed capped
// strings/bytes, and capped lists. Every field has a hard cap so state remains
// bounded; over-cap input fails and is never silently truncated.
//
// Cross-cutting schema rules:
//   - Every command carries an opaque 16-byte request_id for audit
//     correlation. Trusted entries generate one when their external protocol
//     does not provide it; byte ordering and ULID semantics are deliberately
//     not part of the durable contract.
//   - Every command carries an ActorContext, injected by the trusted entry
//     via Propose(command, AuthenticatedPrincipal); apply only copies it into
//     the audit record keyed by raft log index. On the raft-log wire the two
//     actor fields are ordinary bounded strings — they MUST be encoded,
//     otherwise a follower's apply would lose the audit identity. The
//     unforgeability guarantee is a property of the ENTRY layer (only the
//     trusted ctl/coordinator entries can construct commands). External
//     callers cannot supply actor fields; the ctl text-protocol entry injects
//     them before using this internal encoding.
//   - Mutations that require optimistic concurrency carry expected_revision
//     (CAS; conflict is a domain rejection, not a decode failure). A directive
//     result instead identifies an exact live attempt and replays by exact
//     identity/content; apply records its committed index and increments the
//     containing operation revision so an older phase CAS cannot overwrite
//     the new authoritative receipt.
//   - Proposer-authored state changes use absolute values. The receipt-driven
//     operation revision increment above is the deliberate apply-owned
//     exception, derived solely from the committed command and prior state.
//   - Unknown schema versions and unknown command tags are decode failures
//     (fail-stop class); domain validation belongs to the apply layer.
//
// This release supports one command format. Incompatible pre-release bytes
// are rejected instead of negotiated between mixed Meta binaries.

