// Opaque proposal-correlation id (16 bytes, fixed).
using MetaRequestId = std::array<std::uint8_t, 16>;

// operation_id: client-provided stable UUID; the operation's idempotency key
// while its live or archived record remains inside the retention window.
using MetaOperationId = std::array<std::uint8_t, 16>;

// Incarnation-scoped identifiers are generated by the proposer from the OS
// CSPRNG before a command is submitted. Apply treats them as opaque bytes and
// never generates randomness, which keeps replay deterministic.
using MetaAssignmentId = std::array<std::uint8_t, 16>;
using MetaAttemptId = std::array<std::uint8_t, 16>;
using MetaDirectiveId = std::array<std::uint8_t, 16>;

// Opaque proposer-generated identities distinguish a durable transition from
// each replaceable candidate action. Both survive Raft replay and snapshots
// and have no ordering or structure beyond exact equality.
using MetaFailoverTransitionId = std::array<std::uint8_t, 16>;
using MetaFailoverActionId = std::array<std::uint8_t, 16>;

// Content-addressing hashes (intent and manifests):
// SHA-256. Policy replay identity is its bounded exact raw document.
using MetaHash256 = std::array<std::uint8_t, 32>;

// boot_incarnation: opaque fixed-length value, compared only for equality and
// never ordered by magnitude.
inline constexpr std::size_t kMetaBootIncarnationBytes = 20;
using MetaBootIncarnation = std::array<std::uint8_t, kMetaBootIncarnationBytes>;
inline constexpr std::size_t kMetaReplicationHistoryIdBytes = 20;
using MetaReplicationHistoryId =
    std::array<std::uint8_t, kMetaReplicationHistoryIdBytes>;

// Injected by the trusted entry at Propose time. principal_ is the
// canonical SAN principal; readable_time_ is the human-readable propose
// timestamp the trusted entry writes and apply only copies into the audit
// record. Both ride the raft-log encoding as ordinary bounded strings (see
// the file header for why unforgeability is an entry-layer property).
struct ActorContext {
  std::string principal_;
  std::string readable_time_;
  bool operator==(const ActorContext&) const = default;
};

