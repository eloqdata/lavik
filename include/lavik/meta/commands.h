// ---------------------------------------------------------------------------
// operation journal: Submitted -> Running -> Completed |
// Aborted. kind-specific phase-graph legality is checked by coordinator-
// registered ValidateProposal plugins (leader-local), never by apply; the
// schema therefore treats kind and phase blobs as opaque bounded values.
// ---------------------------------------------------------------------------

struct SubmitOperation {
  MetaRequestId request_id_{};
  ActorContext actor_;
  MetaOperationId operation_id_{};  // client-provided stable UUID
  std::string kind_;
  std::string intent_;  // bounded by kMaxMetaPayloadBytes
  MetaHash256 intent_hash_{};
  // All-zero means no replication-history binding. Population tasks use
  // this committed history to bind their target identity.
  MetaReplicationHistoryId replication_history_id_{};
  bool operator==(const SubmitOperation&) const = default;
};

// Canonical desired directive content for one operation phase. Revision is
// intentionally absent: apply assigns the transition's Raft index to new or
// changed directives and retains the prior revision for unchanged entries.
struct MetaDirectiveSpec {
  MetaDirectiveId directive_id_{};
  MetaAttemptId attempt_id_{};
  // Node that executes this directive. Population mutations run on
  // target_node_id_, while source authorization and revocation run on
  // source_node_id_. Keeping this explicit prevents delivery routing from
  // rewriting the durable population identity.
  std::string recipient_node_id_;
  std::string target_node_id_;
  // Incarnation and authority anchors are part of the durable intent. A
  // projector may enrich an envelope with session-local data, but it must not
  // infer these values from whichever topology/grant happens to be current
  // when a directive is replayed after restart.
  MetaBootIncarnation target_boot_id_{};
  // `assignment_id_` is the target membership incarnation carried by the
  // authority anchor. The source has an independent membership lifecycle, so
  // it must be bound explicitly as well: a stable node id surviving
  // remove/re-add is not sufficient authority for population export.
  MetaAssignmentId assignment_id_{};
  std::string source_node_id_;
  MetaAssignmentId source_assignment_id_{};
  MetaBootIncarnation source_boot_id_{};
  MetaReplicationHistoryId source_replication_history_id_{};
  std::string group_id_;
  std::uint64_t group_term_ = 0;
  std::uint64_t population_manifest_revision_ = 0;
  MetaHash256 population_manifest_digest_{};
  std::uint64_t partition_replication_epoch_ = 0;
  std::string kind_;
  // V1 uses payload for initialize-empty-population's authenticated target
  // history and versioned bodies for rebuild/authorize-source source layouts.
  std::string payload_;

  bool operator==(const MetaDirectiveSpec&) const = default;
};

