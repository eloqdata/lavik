// Opaque proposal-correlation id (16 bytes, fixed).
using MetaRequestId = std::array<std::uint8_t, 16>;

// operation_id: client-provided stable UUID; the operation's permanent
// idempotency key.
using MetaOperationId = std::array<std::uint8_t, 16>;

// Incarnation-scoped identifiers are generated by the proposer from the OS
// CSPRNG before a command is submitted. Apply treats them as opaque bytes and
// never generates randomness, which keeps replay deterministic.
using MetaAssignmentId = std::array<std::uint8_t, 16>;
using MetaAttemptId = std::array<std::uint8_t, 16>;
using MetaDirectiveId = std::array<std::uint8_t, 16>;

// Content-addressing hashes (policy content, intent, evidence): SHA-256.
using MetaHash256 = std::array<std::uint8_t, 32>;

// boot_incarnation: opaque fixed-length value, compared only for equality and
// never ordered by magnitude.
inline constexpr std::size_t kMetaBootIncarnationBytes = 20;
using MetaBootIncarnation = std::array<std::uint8_t, kMetaBootIncarnationBytes>;
inline constexpr std::size_t kMetaReplicationHistoryIdBytes = 20;
using MetaReplicationHistoryId =
    std::array<std::uint8_t, kMetaReplicationHistoryIdBytes>;

// Injected by the trusted entry at Propose time. principal_ is the
// canonical SAN principal; readable_time_ is the human-readable propose
// timestamp the trusted entry writes and apply only copies into the audit
// record. Both ride the raft-log encoding as ordinary bounded strings (see
// the file header for why unforgeability is an entry-layer property).
struct ActorContext {
  std::string principal_;
  std::string readable_time_;
  bool operator==(const ActorContext&) const = default;
};

// node_id: 40 lowercase hex chars, matching the data-plane topology
// convention (include/keylane/cluster/topology.h NodeDescriptor::node_id_).
inline constexpr std::uint32_t kMetaNodeIdBytes = 40;
// group_id: opaque to the data plane (topology.h GroupView::group_id_);
// Meta-scoped ids ride the same seam. Bounded as a string.
inline constexpr std::uint32_t kMaxMetaGroupIdBytes = 64;
inline constexpr std::uint32_t kMaxMetaPrincipalBytes = 256;
// Wire cap for ActorContext::readable_time_. Must stay equal to (or tighter
// than) the audit store's persistence cap kMaxMetaAuditReadableTimeBytes
// (audit_store.h), so anything that decodes is persistable.
inline constexpr std::uint32_t kMaxMetaActorReadableTimeBytes = 128;
// One plaintext and one TLS client endpoint, both on the same numeric host.
inline constexpr std::uint32_t kMaxMetaEndpointsPerNode = 2;
inline constexpr std::uint32_t kMaxMetaEndpointBytes = 256;
inline constexpr std::uint32_t kMaxMetaPolicyIdBytes = 128;
inline constexpr std::uint32_t kMaxMetaPolicyReferencesPerOperation = 16;
inline constexpr std::uint32_t kMaxMetaOperationKindBytes = 64;
inline constexpr std::string_view kMetaClusterCreateOperationKind =
    "cluster-create-workflow-v1";
inline constexpr std::string_view kMetaMembershipOperationKind =
    "meta-membership-workflow-v1";
// Keep the original boot/history-bound population kind distinct from the
// new pre-topology workflow. Old WAL entries retain their apply semantics;
// recovery never guesses a full creation intent from a legacy partial task.
inline constexpr std::string_view kMetaClusterCreatePopulationOperationKind =
    "cluster-create-v1";
inline constexpr std::uint32_t kMaxMetaEvidenceSummariesPerCommand = 64;
inline constexpr std::uint32_t kMaxMetaDirectivesPerOperation = 64;
inline constexpr std::uint32_t kMaxMetaDirectiveKindBytes = 64;
// Durable directive names and their execution-side classification live with
// the command schema. Keeping these predicates here prevents stores,
// projectors, and control-session handlers from independently reconstructing
// recipient and mutation semantics when a new kind is appended.
inline constexpr std::string_view kMetaDirectiveRebuild = "rebuild";
inline constexpr std::string_view kMetaDirectiveAuthorizeSource =
    "authorize-source";
inline constexpr std::string_view kMetaDirectiveRevokeSources =
    "revoke-sources";
inline constexpr std::string_view kMetaDirectiveInitializeEmptyPopulation =
    "initialize-empty-population";

inline constexpr bool IsMetaPopulationDirective(std::string_view kind) {
  return kind == kMetaDirectiveRebuild ||
         kind == kMetaDirectiveInitializeEmptyPopulation;
}

inline constexpr bool IsMetaSourceDirective(std::string_view kind) {
  return kind == kMetaDirectiveAuthorizeSource ||
         kind == kMetaDirectiveRevokeSources;
}

inline constexpr bool IsKnownMetaDirective(std::string_view kind) {
  return IsMetaPopulationDirective(kind) || IsMetaSourceDirective(kind);
}

